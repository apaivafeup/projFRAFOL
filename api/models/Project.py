    def get_project_kill_matrix(self):
        return self.tool.get_kill_matrix(self.name_version)
    
    
    def get_project_mutant_killed_list_from_csvs(self, df1, df2):
        ids_df1 = set(df1['Mutant'])
        ids_df2 = set(df2['Mutant'])

        mutant_list = list(ids_df1 - ids_df2)

        return mutant_list

    def backup_generate(self):
        self.clear_project_tools_output()
        d4jh.set_analysis_parameters(self.name_version, self.tool.name, False)
    
    def get_devsuite_path(self):
        '''
        Fetches the dev suite tests related with the given project
        '''
        project = self.name_version
        path = "/root/" + project + "f"

        if not os.path.isdir(path):
            raise ValueError(f"The directory {path} does not exist.")
        
        cmd = "defects4j export -p dir.src.tests"

        result = subprocess.run(cmd, shell=True, cwd=path, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

        src = result.stdout

        cmd = "defects4j query -p " + self.name + " -q classes.relevant.test -o test.csv"
        result = subprocess.run(cmd, shell=True, cwd=path, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

        df = pd.read_csv("/root/" + project + "f/test.csv")
        value = df.isin([int(self.version)])
        row, _ = value.idxmax()
        bin = str(df.iat[row,1])

        bin = bin.replace('.', '/')

        return path + "/" + src + "/" + bin + ".java"

    def get_class_path(self):
        '''
        Fetches the class path of the project's buggy class
        '''
        project = self.name_version
        path = "/root/" + project + "f"
        if not os.path.isdir(path):
            raise ValueError(f"The directory {path} does not exist.")
        
        cmd = "defects4j export -p dir.src.classes"

        result = subprocess.run(cmd, shell=True, cwd=path, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

        src = result.stdout

        cmd = "defects4j export -p classes.modified"

        result = subprocess.run(cmd, shell=True, cwd=path, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

        bin = result.stdout

        bin = bin.replace('.', '/')

        return path + "/" + src + "/" + bin + ".java"